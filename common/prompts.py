def _render_schema() -> str:
    lines = []
    for key, description in OUTPUT_SCHEMA.items():
        lines.append(f"- {key}: {description}")
    return "\n".join(lines)


def _render_examples() -> str:
    blocks = []
    for number, example in enumerate(EXAMPLES, start=1):
        dialogue = "\n".join(f"{turn['role']}: {turn['text']}" for turn in example["dialogue"])
        card = json.dumps(example["card"], ensure_ascii=False, indent=2)
        blocks.append(f"### Пример {number}\nДиалог:\n{dialogue}\nОтвет:\n{card}")
    return "\n\n".join(blocks)


def _render_segments() -> str:
    known = segments()
    lines = []
    for code, markers in DEFINITIONS:
        lines.append(f"- {code} — «{known.get(code, code)}». {markers}")
    return "\n".join(lines)


def _render_knowledge() -> str:
    return "\n".join(f"- {item['id']} ({item['topic']}): {item['text']}" for item in knowledge_items())


def _render_list(items: list[str], start: int = 1) -> str:
    return "\n".join(f"{index + start}. {text}" for index, text in enumerate(items))


def _render_forbidden() -> str:
    return "\n".join(f"- не {text}" for text in FORBIDDEN)


